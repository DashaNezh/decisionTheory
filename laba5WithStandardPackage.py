from scipy.optimize import linprog

# Целевая функция (коэффициенты для минимизации)
c = [-1, 1]  # Мы минимизируем - (x1 - x2)

# Ограничения
A = [
    [1, -1],   # x1 - x2 <= -8
    [8, 5],    # 8x1 + 5x2 <= 80
    [1, -2],   # x1 - 2x2 <= 2
    [1, 4]     # x1 + 4x2 >= 4 (переписываем как <=)
]

b = [-8, 80, 2, 4]  # Правая часть ограничений

# Изменяем знак для последнего ограничения
A[-1] = [-1 * a for a in A[-1]]
b[-1] = -b[-1]

# Решаем задачу
res = linprog(c, A_ub=A, b_ub=b, bounds=(0, None))

# Вывод результатов
if res.success:
    print(f"Максимальное значение целевой функции: {res.fun * -1}")  # Умножаем на -1, чтобы получить максимальное значение
    print(f"Значения переменных: x1 = {res.x[0]}, x2 = {res.x[1]}")
else:
    print("Не удалось найти решение.")
